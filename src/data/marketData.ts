export type Timeframe = '1D' | '5D' | '1M' | '6M' | 'YTD' | '1Y' | 'ALL';

export type CategoryTab =
  | 'Indices'
  | 'US stocks'
  | 'World stocks'
  | 'Crypto'
  | 'Futures & commodities'
  | 'Forex & currencies'
  | 'Government bonds'
  | 'Corporate bonds'
  | 'ETFs'
  | 'Economy';

export interface ChartPoint {
  x: number;
  y: number;
  label: string;
  price: string;
}

export interface BenchmarkIndex {
  id: string;
  name: string;
  fullName: string;
  tickerSubtitle: string;
  symbol: string;
  badgeText: string;
  badgeBg: string;
  badgeTextSize?: string;
  price: string;
  numericPrice: number;
  changePercent: string;
  changePoints: string;
  isPositive: boolean;
  category: CategoryTab;
  timeframes: Record<
    Timeframe,
    {
      changePoints: string;
      changePercent: string;
      isPositive: boolean;
      linePath: string;
      areaPath: string;
      endY: number;
      points: ChartPoint[];
    }
  >;
}

export interface MarketRowItem {
  id: string;
  symbol: string;
  name: string;
  subtitle: string;
  badgeText: string;
  badgeBg: string;
  badgeTextColor: string;
  badgeTextSize?: string;
  price: string;
  changePercent: string;
  changePoints: string;
  isPositive: boolean;
  category: 'world-indices' | 'us-stocks' | 'crypto' | 'forex' | 'commodities' | 'bonds' | 'etfs';
  volume?: string;
  marketCap?: string;
  high52W?: string;
  low52W?: string;
}

export interface SecondaryAsset {
  id: string;
  categoryLabel: string;
  name: string;
  subtitle: string;
  price: string;
  change: string;
  isPositive: boolean;
  symbol: string;
}

export interface EarningsReport {
  id: string;
  symbol: string;
  company: string;
  dateLabel: string;
  estimate: string;
  actual: string;
  quarter: string;
  marketCap: string;
  timeOfDay: 'Before Market Open' | 'After Market Close';
}

